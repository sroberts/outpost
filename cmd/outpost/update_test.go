// With no daemon, an update installs the binary and records the release, and
// leaves the rest of the manifest exactly as the operator had it.
func TestUpdate_FromRecordsTheSourceAndKeepsTheManifest(t *testing.T) {
	home := t.TempDir()
	path := declareInstalled(t, home, "svc", []byte("old"), freePort(t), "")
	before := readFile(t, path)
	useFakeGitHub(t, fakeGitHub(t, []byte("new"), "", true))

	stdout, stderr, err := runCLI(t, home, "update", "svc", "--from", "https://github.com/o/r")
	if err != nil {
		t.Fatalf("update: %v\n%s", err, stderr)
	}
	if got := readFile(t, filepath.Join(home, "bin", "svc")); got != "new" {
		t.Errorf("binary = %q; want the release's", got)
	}
	if got := readFile(t, filepath.Join(home, "bin", "svc.previous")); got != "old" {
		t.Errorf("previous binary = %q; want the one replaced", got)
	}
	after := readFile(t, path)
	for _, line := range strings.SplitAfter(before, "\n") {
		if !strings.Contains(after, line) {
			t.Errorf("manifest lost %q:\n%s", line, after)
		}
	}
	svc, err := manifest.Load(path)
	if err != nil {
		t.Fatalf("updated manifest does not load: %v\n%s", err, after)
	}
	if svc.Source != "o/r" || svc.Release != "v1.2.3" {
		t.Errorf("source, release = %q, %q; want o/r, v1.2.3", svc.Source, svc.Release)
	}
	if !strings.Contains(stdout, "when the daemon next starts it") {
		t.Errorf("stdout does not say when it takes effect:\n%s", stdout)
	}
	if !strings.Contains(stderr, "no backup was taken") {
		t.Errorf("stderr does not say the backup was skipped:\n%s", stderr)
	}
}

