// declareInstalled writes a service as `outpost add` would have left it: a
// binary under <home>/bin and a manifest naming where it came from. The
// manifest carries a comment and a hand edit, which an update must keep.
func declareInstalled(t *testing.T, home, name string, binary []byte, port int, release string) string {
	t.Helper()
	for _, dir := range []string{"bin", "services"} {
		if err := os.MkdirAll(filepath.Join(home, dir), 0o700); err != nil {
			t.Fatal(err)
		}
	}
	bin := filepath.Join(home, "bin", name)
	if err := os.WriteFile(bin, binary, 0o755); err != nil {
		t.Fatal(err)
	}
	var src string
	if release != "" {
		src = fmt.Sprintf("source         = \"o/r\"\nrelease        = %q\n", release)
	}
	body := fmt.Sprintf(`# %s — generated by `+"`outpost add`"+`
name           = %q
runtime        = "process"
binary         = %q
%sargs           = ["--port", "%d"]
port           = %d
storage        = %q
healthcheck    = "/up"
restart_policy = "on-failure"
# kept by hand: an operator's note
`, name, name, bin, src, port, port, filepath.Join(home, "data", name))
	path := filepath.Join(home, "services", name+".toml")
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

