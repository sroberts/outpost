func TestSetRelease(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{
			"replaces both in place",
			"name = \"a\"\nsource = \"x/y\"\nrelease = \"v1\"\nport = 1\n",
			"name = \"a\"\nsource         = \"o/r\"\nrelease        = \"v2\"\nport = 1\n",
		},
		{
			"adds them at the end",
			"name = \"a\"\n# note\n",
			"name = \"a\"\n# note\nsource         = \"o/r\"\nrelease        = \"v2\"\n",
		},
		{
			"with no final newline",
			"name = \"a\"",
			"name = \"a\"\nsource         = \"o/r\"\nrelease        = \"v2\"\n",
		},
		{
			// Below a [table] header a key belongs to the table, and an env
			// var called source is the service's business.
			"stays above a table",
			"name = \"a\"\n[env]\nsource = \"mine\"\n",
			"name = \"a\"\nsource         = \"o/r\"\nrelease        = \"v2\"\n[env]\nsource = \"mine\"\n",
		},
	}
	for _, tc := range cases {
		if got := string(setRelease([]byte(tc.in), "o/r", "v2")); got != tc.want {
			t.Errorf("%s:\ngot:\n%s\nwant:\n%s", tc.name, got, tc.want)
		}
	}
}

// --- against a running daemon ---

var (
	fakeOnce sync.Once
	fakeBin  string
	fakeErr  error
)

// fakeservice builds the runtime package's stand-in service once.
func fakeservice(t *testing.T) string {
	t.Helper()
	fakeOnce.Do(func() {
		dir, err := os.MkdirTemp("", "outpost-fakeservice")
		if err != nil {
			fakeErr = err
			return
		}
		fakeBin = filepath.Join(dir, "fakeservice")
		out, err := exec.Command("go", "build", "-o", fakeBin, "../../internal/runtime/testdata/fakeservice").CombinedOutput()
		if err != nil {
			fakeErr = fmt.Errorf("build fakeservice: %v\n%s", err, out)
		}
	})
	if fakeErr != nil {
		t.Fatal(fakeErr)
	}
	return fakeBin
}

// runDaemon serves home's services over its socket, as `outpost serve` does,
// minus the tailnet and the gateway. home must be short enough for a socket.
func runDaemon(t *testing.T, home string) *ipc.Client {
	t.Helper()
	store, err := state.Open(filepath.Join(home, "state.db"))
	if err != nil {
		t.Fatal(err)
	}
	sup, err := supervisor.New(supervisor.Options{
		ServicesDir:    filepath.Join(home, "services"),
		Store:          store,
		ProcessRuntime: &runtime.ProcessRuntime{LogDir: filepath.Join(home, "logs")},
		BackupDir:      filepath.Join(home, "backups"),
		Interval:       50 * time.Millisecond,
	})
	if err != nil {
		t.Fatal(err)
	}
	if err := sup.Apply(context.Background()); err != nil {
		t.Fatal(err)
	}
	srv, err := ipc.Listen(filepath.Join(home, "outpost.sock"), sup, nil)
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	loopDone, serveDone := make(chan struct{}), make(chan struct{})
	go func() { defer close(loopDone); _ = sup.Run(ctx) }()
	go func() { defer close(serveDone); _ = srv.Serve(ctx) }()
	t.Cleanup(func() {
		_ = sup.Shutdown(context.Background())
		cancel()
		srv.Close()
		<-serveDone
		<-loopDone
		store.Close()
	})
	return ipc.NewClient(filepath.Join(home, "outpost.sock"))
}

// daemonHome is an Outpost home with svc installed at v1.0.0 from
// fakeservice, running under a daemon, and healthy.
func daemonHome(t *testing.T) (string, *ipc.Client, []byte) {
	t.Helper()
	home, err := os.MkdirTemp("", "op")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(home) })
	original, err := os.ReadFile(fakeservice(t))
	if err != nil {
		t.Fatal(err)
	}
	declareInstalled(t, home, "svc", original, freePort(t), "v1.0.0")

	prev := updatePoll
	updatePoll = 50 * time.Millisecond
	t.Cleanup(func() { updatePoll = prev })

	c := runDaemon(t, home)
	svc, err := manifest.Load(filepath.Join(home, "services", "svc.toml"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := waitHealthy(c, svc, "", 10*time.Second); err != nil {
		t.Fatalf("svc never came up: %v", err)
	}
	return home, c, original
}

// The whole point: a new release replaces the old one and is running and
// healthy when the command returns, with a backup taken first.
func TestUpdate_RestartsOntoTheNewRelease(t *testing.T) {
	home, c, _ := daemonHome(t)
	before, err := c.Status("svc")
	if err != nil {
		t.Fatal(err)
	}
	// A different file from the installed one that still runs the service.
	release := []byte("#!/bin/sh\nexec " + fakeservice(t) + " \"$@\"\n")
	useFakeGitHub(t, fakeGitHub(t, release, "", true))

	stdout, stderr, err := runCLI(t, home, "update", "svc")
	if err != nil {
		t.Fatalf("update: %v\nstdout: %s\nstderr: %s", err, stdout, stderr)
	}
	if !strings.Contains(stdout, "running v1.2.3 and healthy (was v1.0.0)") {
		t.Errorf("stdout = %s", stdout)
	}
	if !bytes.Equal([]byte(readFile(t, filepath.Join(home, "bin", "svc"))), release) {
		t.Error("the binary is not the release's")
	}
	after, err := c.Status("svc")
	if err != nil {
		t.Fatal(err)
	}
	if after.InstanceID == before.InstanceID {
		t.Error("the service was not restarted onto the new binary")
	}
	backups, err := c.Backups("svc")
	if err != nil || len(backups) != 1 {
		t.Errorf("backups = %v, %v; want one taken before updating", backups, err)
	}
}

// A release that will not come up healthy must not be left in place.
func TestUpdate_RollsBackAReleaseThatFailsItsHealthcheck(t *testing.T) {
	home, c, original := daemonHome(t)
	path := filepath.Join(home, "services", "svc.toml")
	manifestBefore := readFile(t, path)
	useFakeGitHub(t, fakeGitHub(t, []byte("#!/bin/sh\nexit 1\n"), "", true))

	_, stderr, err := runCLI(t, home, "update", "svc", "--wait", "2s")
	if err == nil {
		t.Fatalf("update of a broken release succeeded\nstderr: %s", stderr)
	}
	if !strings.Contains(err.Error(), "rolled back to v1.0.0, which is running and healthy") {
		t.Errorf("err = %v", err)
	}
	if !bytes.Equal([]byte(readFile(t, filepath.Join(home, "bin", "svc"))), original) {
		t.Error("the old binary was not put back")
	}
	if got := readFile(t, path); got != manifestBefore {
		t.Errorf("manifest not restored:\n%s", got)
	}
	st, err := c.Status("svc")
	if err != nil {
		t.Fatal(err)
	}
	if st.Status != "running" {
		t.Errorf("status after rollback = %s", st.Status)
	}
}

