	path := declareInstalled(t, home, "svc", []byte("old"), freePort(t), "v1.0.0")
	elsewhere := filepath.Join(t.TempDir(), "svc")
	if err := os.WriteFile(elsewhere, []byte("theirs"), 0o755); err != nil {
		t.Fatal(err)
	}
	body := strings.Replace(readFile(t, path), filepath.Join(home, "bin", "svc"), elsewhere, 1)
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	useFakeGitHub(t, fakeGitHub(t, []byte("new"), "", true))

	_, _, err := runCLI(t, home, "update", "svc")
